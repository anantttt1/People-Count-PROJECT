-- =====================================================================
-- Smart Vision AI - Supabase PostgreSQL schema
-- Run once in Supabase Dashboard → SQL Editor → New query → Run.
-- Safe to re-run (IF NOT EXISTS everywhere).
--
-- Privacy: only numeric analytics are stored. No images, no video,
-- no faces, no identities, no IP addresses.
-- =====================================================================

-- One row per counting run
create table if not exists public.sessions (
    id               uuid primary key,
    name             text not null check (char_length(name) between 1 and 80),
    started_at       timestamptz not null default now(),
    ended_at         timestamptz,
    status           text not null default 'running'
                     check (status in ('running', 'completed', 'interrupted')),
    detector         text,
    total_entries    integer not null default 0 check (total_entries >= 0),
    total_exits      integer not null default 0 check (total_exits >= 0),
    max_occupancy    integer not null default 0,
    peak_live_count  integer not null default 0 check (peak_live_count >= 0),
    frames_processed integer not null default 0 check (frames_processed >= 0),
    settings         jsonb,
    heatmap          jsonb,          -- coarse grid of counts (e.g. 32x18), no images
    created_at       timestamptz not null default now()
);
create index if not exists idx_sessions_started on public.sessions (started_at desc);

-- Entry / exit crossings and capacity alerts
create table if not exists public.events (
    id               uuid primary key,             -- generated by the backend (idempotent retries)
    session_id       uuid not null references public.sessions (id) on delete cascade,
    event_type       text not null
                     check (event_type in ('entry', 'exit', 'capacity_exceeded', 'capacity_cleared')),
    occurred_at      timestamptz not null,
    occupancy_after  integer not null,
    live_count       integer not null default 0 check (live_count >= 0)
);
create index if not exists idx_events_time on public.events (occurred_at);
create index if not exists idx_events_session on public.events (session_id, occurred_at);

-- Periodic occupancy samples (every SNAPSHOT_INTERVAL_SECONDS per running session)
create table if not exists public.occupancy_snapshots (
    id               uuid primary key,
    session_id       uuid not null references public.sessions (id) on delete cascade,
    captured_at      timestamptz not null,
    avg_live_count   real not null check (avg_live_count >= 0),
    max_live_count   integer not null check (max_live_count >= 0),
    occupancy        integer not null,
    fps              real
);
create index if not exists idx_snapshots_session on public.occupancy_snapshots (session_id, captured_at);

-- Admin defaults (single row)
create table if not exists public.app_settings (
    id         smallint primary key default 1 check (id = 1),
    data       jsonb not null,
    updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Row Level Security
-- RLS is ON for every table and there are NO policies for the `anon`
-- or `authenticated` roles, so the public anon key can't read or write
-- anything. The FastAPI backend uses the service_role key (server-side
-- only), which bypasses RLS by design.
-- ---------------------------------------------------------------------
alter table public.sessions            enable row level security;
alter table public.events              enable row level security;
alter table public.occupancy_snapshots enable row level security;
alter table public.app_settings        enable row level security;

revoke all on public.sessions, public.events, public.occupancy_snapshots, public.app_settings
    from anon, authenticated;

